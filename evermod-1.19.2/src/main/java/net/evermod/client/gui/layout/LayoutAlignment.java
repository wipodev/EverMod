package net.evermod.client.gui.layout;

/**
 * Alignment options for components inside Column and Row layouts.
 *
 * @author Wipodev
 */
public enum LayoutAlignment {
  /** Align components to the start (Left in Column, Top in Row). */
  START,
  /** Center components along the cross axis. */
  CENTER,
  /** Align components to the end (Right in Column, Bottom in Row). */
  END
}
